@router.get("/live-overlay/source/effects/{token}/events", include_in_schema=False)
def effects_source_events(token: str, after: int = 0):
    user_id = _user_for_source(token)
    after = max(0, min(int(after), 2_147_483_647))
    with _connect() as con:
        rows = con.execute(
            "SELECT id,event_type,payload_json,created_at FROM live_overlay_events WHERE user_id=? AND id>? ORDER BY id ASC LIMIT 100",
            (user_id, after),
        ).fetchall()
    events = []
    for row in rows:
        try:
            payload = json.loads(str(row["payload_json"]))
        except Exception:
            payload = {}
        events.append(
            {
                "id": int(row["id"]),
                "event_type": str(row["event_type"]),
                "payload": payload if isinstance(payload, dict) else {},
                "created_at": row["created_at"],
            }
        )
    return JSONResponse(
        {"events": events},
        headers={"Cache-Control": "no-store", "Referrer-Policy": "no-referrer"},
    )


def _catalog_html() -> str:
    categories: dict[str, list[dict]] = {}
    for item in EFFECT_CATALOG:
        categories.setdefault(item["category"], []).append(item)
    chunks = []
    for category, items in categories.items():
        rows = "".join(
            f"<label class='fx'><input type='checkbox' data-fx='{escape(item['id'], quote=True)}'>"
            f"<span><b>{escape(item['name'])}</b><small>{escape(item['description'])}</small>"
            f"<em>{escape(', '.join(item['events']))}</em></span></label>"
            for item in items
        )
        chunks.append(f"<section class='group'><h2>{escape(category)}</h2><div class='grid'>{rows}</div></section>")
    return "".join(chunks)


