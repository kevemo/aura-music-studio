EFFECT_BY_ID = {item["id"]: item for item in EFFECT_CATALOG}
DEFAULT_ENABLED = [item["id"] for item in EFFECT_CATALOG if item["default_enabled"]]


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _connect() -> sqlite3.Connection:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys=ON")
    con.execute("PRAGMA journal_mode=WAL")
    return con


def _init_schema() -> None:
    with _connect() as con:
        con.executescript(
            """
            CREATE TABLE IF NOT EXISTS live_overlay_effect_preferences (
                user_id TEXT PRIMARY KEY,
                enabled_json TEXT NOT NULL,
                intensity REAL NOT NULL DEFAULT 1.0,
                max_effects_per_event INTEGER NOT NULL DEFAULT 6,
                reduced_motion INTEGER NOT NULL DEFAULT 0,
                updated_at TEXT NOT NULL
            );
            """
        )


_init_schema()


def _member(request: Request):
    member = getattr(request.state, "member", None)
    if member is None:
        raise HTTPException(401, "Sign in required")
    return member


def _user_for_source(token: str) -> str:
    digest = _hash_token(token)
    with _connect() as con:
        row = con.execute(
            "SELECT user_id FROM live_overlay_profiles WHERE source_token_hash=?",
            (digest,),
        ).fetchone()
    if not row:
        raise HTTPException(404, "Overlay source not found")
    return str(row["user_id"])


def _preferences(user_id: str) -> dict:
    with _connect() as con:
        row = con.execute(
            "SELECT * FROM live_overlay_effect_preferences WHERE user_id=?",
            (user_id,),
        ).fetchone()
        if not row:
            con.execute(
                """INSERT INTO live_overlay_effect_preferences(
                       user_id,enabled_json,intensity,max_effects_per_event,reduced_motion,updated_at
                   ) VALUES(?,?,1.0,6,0,?)""",
                (user_id, json.dumps(DEFAULT_ENABLED), _now()),
            )
            row = con.execute(
                "SELECT * FROM live_overlay_effect_preferences WHERE user_id=?",
                (user_id,),
            ).fetchone()
    try:
        enabled = json.loads(str(row["enabled_json"]))
    except Exception:
        enabled = list(DEFAULT_ENABLED)
    enabled = [effect_id for effect_id in enabled if effect_id in EFFECT_BY_ID]
    return {
        "enabled_effects": enabled,
        "intensity": max(0.25, min(float(row["intensity"]), 2.0)),
        "max_effects_per_event": max(1, min(int(row["max_effects_per_event"]), MAX_EFFECTS_PER_EVENT)),
        "reduced_motion": bool(row["reduced_motion"]),
        "updated_at": row["updated_at"],
    }


def effect_state_for_user(user_id: str) -> dict:
    prefs = _preferences(user_id)
    enabled = set(prefs["enabled_effects"])
    return {
        **prefs,
        "catalog": [{**item, "enabled": item["id"] in enabled} for item in EFFECT_CATALOG],
        "effect_count": len(EFFECT_CATALOG),
        "all_effects_selectable": True,
        "event_input": "normalized_live_overlay_events",
        "browser_source_runtime": True,
        "arbitrary_javascript_execution": False,
    }


